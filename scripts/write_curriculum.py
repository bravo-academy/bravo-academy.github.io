def write_one(key, titles):
    g, sub = key.split("_", 1)
    n = int(g[1])
    lessons = []
    for i, t in enumerate(titles, 1):
        lessons.append({
            "id": f"{i:02d}",
            "title": t,
            "status": "ready" if (n == 3 and i == 1 and sub in ("math", "arabic", "science", "french", "islamic", "civic")) or (n == 3 and i <= 4 and sub == "math") else "planned",
        })
    # mark first of each g3 subject as we will produce them
    data = {
        "level": g,
        "level_ar": LEVELS[n],
        "subject": sub,
        "subject_ar": SUBJECTS[sub],
        "lessons": lessons,
    }
    path = os.path.join(CUR, f"{g}_{sub}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("wrote", path, len(lessons))

for k, v in PROG.items():
    write_one(k, v)

